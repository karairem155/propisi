/** Harfin hamle yolu — yoksa null (o zaman eski jeodezik gösterim). */
export function hamleOf(ch: string): Yol[][] | null {
  const raw = HAMLELER[ch];
  if (!raw) return null;
  return raw.map((stroke) => stroke.map(([x, y]) => ({ x, y })));
}

/** Kaç harfin verisi var — tanılama ekranı gösteriyor. */
export function hamleCount(): number {
  return Object.keys(HAMLELER).length;
}
